    fun forProfile(profileId: String) = BrowserIdentityConfig(
        profileId = profileId,
        presetId = id,
        userAgent = userAgent,
        platform = platform,
        operatingSystem = operatingSystem,
        viewportWidth = viewportWidth,
        viewportHeight = viewportHeight,
