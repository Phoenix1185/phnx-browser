        colorDepth = colorDepth,
        deviceScaleFactor = deviceScaleFactor,
        locale = locale,
        language = language,
        languages = languages,
        timezone = timezone,
        touchSupport = touchSupport,
        mobileMode = mobileMode,
        clientHints = clientHints,
    )
}

